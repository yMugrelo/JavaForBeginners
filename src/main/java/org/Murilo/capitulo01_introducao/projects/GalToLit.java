package org.Murilo.capitulo01_introducao.projects;

public class GalToLit {
    static void main(String[] args) {
        double gallons;
        double liters;

        gallons = 10.0;
        liters = gallons * 3.7854;

        System.out.println(gallons + " Gallon is: " + liters + "Liters" );

        System.out.println();
    }
}
