package org.Murilo.capitulo02;

public class ModDemo {
    static void main(String[] args) {


        int iresult, irem;
        double dresult, drem;

        iresult = 10 / 3;
        irem = 10 % 3;

        dresult = 10 / 3;
        drem = 10 % 3;

        System.out.println("Result and remainder of 10/3: " + iresult + ", " + irem);
        System.out.println("Result and remainder of 10/3: " + dresult + ", " + drem);
    }
}
